<?php

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

/*
|--------------------------------------------------------------------------
| ROOT PATH
|--------------------------------------------------------------------------
*/

define('ROOT_PATH', dirname(__DIR__, 2));

/*
|--------------------------------------------------------------------------
| DATABASE FILE
|--------------------------------------------------------------------------
*/

require_once ROOT_PATH . '/config/database.php';

/*
|--------------------------------------------------------------------------
| DATABASE CONNECTION
|--------------------------------------------------------------------------
*/

$database = new Database();
$conn = $database->connect();

/*
|--------------------------------------------------------------------------
| CHECK CONNECTION
|--------------------------------------------------------------------------
*/

if (!$conn) {
    die("Database connection failed.");
}